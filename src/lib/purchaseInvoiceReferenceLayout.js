const NAVY=[13,32,70], BLUE=[22,104,233], CYAN=[0,191,218], FADED=[99,116,140], LIGHT=[239,248,255],
 BORDER=[221,233,245], GREEN=[0,154,107], RED=[217,48,78];
const currencyAmount=(n,c)=>new Intl.NumberFormat('en-US',{minimumFractionDigits:2,maximumFractionDigits:2}).format(Number(n)||0)+' '+c;
const display=(x)=>x===null||x===undefined||String(x).trim()===''?'—':String(x).trim();
const shorten=(x,length)=>{const s=display(x);return s.length>length?s.slice(0,length-1)+'…':s;};
const firstStr=(...values)=>values.find(v=>v!==null&&v!==undefined&&String(v).trim()!=='')||null;
function wrapWords(input,max=32){
 const words=display(input).split(/\s+/),lines=[];let line='';
 for(const word of words){
  if(line&&line.length+word.length+1>max){lines.push(line);line='';}
  if(word.length>max){
   if(line){lines.push(line);line='';}
   for(let i=0;i<word.length;i+=max)lines.push(word.slice(i,i+max));
  }else line=line?line+' '+word:word;
 }
 if(line)lines.push(line);
 return lines.length?lines:['—'];
}
export function invoiceApprovalSteps(invoice,history=[]){
 const steps=[];
 if(invoice.created_date)steps.push({type:'created',date:invoice.created_date,who:invoice.created_by||null});
 const rows=(Array.isArray(history)?history:[]).sort((a,b)=>String(a.created_date||'').localeCompare(String(b.created_date||'')));
 const reviewed=rows.find(x=>/review|مراجع/i.test(String(x.action||'')));
 if(reviewed)steps.push({type:'reviewed',date:reviewed.created_date,who:reviewed.user_name||null});
 const status=invoice.approval_status;
 if(['approved','auto_approved'].includes(status)){
  const event=rows.find(x=>/approv/i.test(String(x.action||'')));
  steps.push({type:status==='auto_approved'?'auto':'approved',
   date:event?.created_date||null,who:event?.user_name||null});
 }
 if(status==='pending' && !steps.some(x=>x.type==='pending'))steps.push({type:'pending',date:null});
 return steps;
}
export function invoicePaymentLabel(invoice,payments=[],language='en'){
 const w=LANGUAGE[language]||LANGUAGE.en;
 const methods=[...new Set((Array.isArray(payments)?payments:[])
  .map(p=>String(p.payment_method||'').trim()).filter(Boolean))];
 if(!methods.length)return firstStr(invoice.payment_method)||w.unknown;
 return methods.length===1?methods[0]:w.paymentMixed;
}
